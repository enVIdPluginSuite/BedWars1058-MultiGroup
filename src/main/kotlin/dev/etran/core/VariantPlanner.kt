package dev.etran.core

import java.util.Locale

/** A map's own BedWars1058 arena (`plugins/BedWars1058/Arenas/<name>.yml`), the base of all of its variants. */
data class BaseArena(val name: String, val group: String, val tree: Map<String, Any?>)

/** Settings that shape the generated variant arenas. */
data class PlanSettings(
    /** `{map}` and `{group}`; the result is lower-cased (BedWars1058 lower-cases arena names itself) and sanitised. */
    val namePattern: String = "{map}-{group}",
    /** `{display}` (the base arena's display name), `{map}`, `{group}`, `{config}`. */
    val displayNameFormat: String = "{display}",
    /** Sections that a configuration replaces as a whole instead of merging into (dotted paths). */
    val replaceSections: Set<String> = setOf("Team"),
    /** When no configuration matches a group: true = play the base configuration, false = skip that group. */
    val fallbackToBase: Boolean = true,
)

/** One arena that will be generated: map [map] played in [group] with configuration [match]. */
data class VariantPlan(
    val arenaName: String,
    val map: String,
    val group: String,
    val match: MatchResult,
    val tree: LinkedHashMap<String, Any?>,
) {
    val key: String get() = arenaName.lowercase(Locale.ROOT)
}

data class Plan(
    val variants: List<VariantPlan>,
    val warnings: List<String>,
    /** Groups used by variants that BedWars1058's `arenaGroups` does not contain yet (BedWars would put them in "Default"). */
    val unknownGroups: List<String>,
)

/**
 * Turns map definitions into the list of variant arenas to generate. Pure logic: the caller supplies everything
 * read from disk, so the decision process can be tested (and previewed with `/bwmg info`) without a server.
 */
class VariantPlanner(private val matcher: ConfigMatcher, private val settings: PlanSettings) {

    fun plan(
        maps: List<MapDefinition>,
        bases: Map<String, BaseArena>,
        bedwarsGroups: List<String>,
        /** lower-case names of arena files that were NOT generated by this plugin */
        foreignArenas: Set<String>,
    ): Plan {
        val warnings = ArrayList<String>()
        val variants = ArrayList<VariantPlan>()
        val used = HashMap<String, String>() // variant key -> "map/group"
        val unknown = LinkedHashMap<String, String>()
        val groupCasing = bedwarsGroups.associateBy { it.lowercase(Locale.ROOT) }

        for (def in maps.sortedBy { it.key }) {
            if (!def.enabled) continue
            val base = bases[def.key]
            if (base == null) {
                warnings += "Map '${def.name}': there is no arena configuration plugins/BedWars1058/Arenas/${def.name}.yml, so it has no variants."
                continue
            }
            for (rawGroup in expandGroups(def, bedwarsGroups, warnings)) {
                val group = groupCasing[rawGroup.lowercase(Locale.ROOT)] ?: rawGroup
                if (group.equals(base.group, ignoreCase = true)) continue // that is the base arena itself
                val name = variantName(base.name, group)
                if (name == null) {
                    warnings += "Map '${def.name}', group '$group': the arena name pattern '${settings.namePattern}' gives an empty name."
                    continue
                }
                val key = name.lowercase(Locale.ROOT)
                if (key == def.key || bases.containsKey(key) || key in foreignArenas) {
                    warnings += "Map '${def.name}', group '$group': an arena called '$name' already exists and was not created by " +
                        "BedWars1058-MultiGroup, so this variant is skipped. If it is a copy of '${def.name}', absorb it with " +
                        "/bwmg import ${def.name} $name"
                    continue
                }
                val other = used[key]
                if (other != null) {
                    warnings += "Map '${def.name}', group '$group': the variant name '$name' is already used by $other; skipped. " +
                        "Change variant-name-pattern so that every map/group pair gets its own name."
                    continue
                }

                val match = matcher.match(group, def.configs.map { it.candidate() }, def.explicitFor(group))
                if (match.config == null && !settings.fallbackToBase) {
                    warnings += "Map '${def.name}', group '$group': ${match.reason}; skipped (fallback-to-base is off)."
                    continue
                }
                if (match.ambiguous) {
                    warnings += "Map '${def.name}', group '$group': '${match.config}' and '${match.runnerUp}' match equally well; " +
                        "'${match.config}' was chosen. Set group-configs.$group in maps/${def.name}.yml to decide."
                }
                if (!groupCasing.containsKey(group.lowercase(Locale.ROOT))) unknown.putIfAbsent(group.lowercase(Locale.ROOT), group)
                used[key] = "${def.name}/$group"
                variants += VariantPlan(name, base.name, group, match, buildTree(base, def, match.config, group))
            }
        }
        return Plan(variants, warnings, unknown.values.toList())
    }

    /** The complete arena configuration of one variant. */
    fun buildTree(base: BaseArena, def: MapDefinition, configName: String?, group: String): LinkedHashMap<String, Any?> {
        val replace: (String) -> Boolean = { it in settings.replaceSections }
        var tree = TreeMerge.deepCopy(base.tree)
        tree.remove(MARKER_SECTION)
        if (def.shared.isNotEmpty()) tree = TreeMerge.merge(tree, def.shared, replace)
        val cfg = configName?.let { def.config(it) }
        if (cfg != null) {
            for (path in cfg.remove) TreeMerge.remove(tree, path)
            tree = TreeMerge.merge(tree, cfg.overrides, replace)
        }
        tree.remove(MARKER_SECTION)
        tree["group"] = group

        val baseDisplay = (base.tree[DISPLAY_NAME] as? String)?.trim().orEmpty().ifEmpty { prettyName(base.name) }
        val ownDisplay = (cfg?.overrides?.get(DISPLAY_NAME) as? String)?.trim().orEmpty()
        tree[DISPLAY_NAME] = ownDisplay.ifEmpty {
            settings.displayNameFormat
                .replace("{display}", baseDisplay)
                .replace("{map}", base.name)
                .replace("{group}", group)
                .replace("{config}", configName ?: ConfigMatcher.BASE)
        }

        val marker = LinkedHashMap<String, Any?>()
        marker["generated"] = true
        marker["map"] = base.name
        marker["group"] = group
        marker["config"] = configName ?: ConfigMatcher.BASE
        marker["note"] = "Generated by BedWars1058-MultiGroup and rewritten on every start. " +
            "Edit plugins/BedWars1058-MultiGroup/maps/${base.name}.yml instead."
        tree[MARKER_SECTION] = marker
        return tree
    }

    /** `{map}-{group}` -> `lighthouse-solorush`; null when nothing usable is left. */
    fun variantName(map: String, group: String): String? {
        val raw = settings.namePattern.replace("{map}", map).replace("{group}", group).lowercase(Locale.ROOT)
        val clean = raw.replace(INVALID_NAME_CHARS, "_").replace(REPEATED_UNDERSCORE, "_").trim('_')
        return clean.ifEmpty { null }
    }

    private fun expandGroups(def: MapDefinition, bedwarsGroups: List<String>, warnings: MutableList<String>): List<String> {
        val out = LinkedHashMap<String, String>()
        for (entry in def.groups) {
            if (entry.contains('*') || entry.contains('?')) {
                val rx = globToRegex(entry)
                val hits = bedwarsGroups.filter { rx.matches(it) }
                if (hits.isEmpty()) warnings += "Map '${def.name}': the group pattern '$entry' matches none of BedWars1058's arenaGroups."
                hits.forEach { out.putIfAbsent(it.lowercase(Locale.ROOT), it) }
            } else {
                out.putIfAbsent(entry.lowercase(Locale.ROOT), entry)
            }
        }
        return out.values.toList()
    }

    companion object {
        /** Section written into every generated arena file; its presence is how generated files are recognised. */
        const val MARKER_SECTION = "multigroup"
        const val DISPLAY_NAME = "display-name"

        // Minecraft 1.16+ turns world names into lower-case namespaced keys: only a-z 0-9 _ - . are safe.
        private val INVALID_NAME_CHARS = Regex("[^a-z0-9_.-]")
        private val REPEATED_UNDERSCORE = Regex("_{2,}")

        /** BedWars1058's default display name for an arena name. */
        fun prettyName(arena: String): String =
            if (arena.isEmpty()) arena else (arena[0].uppercaseChar() + arena.substring(1)).replace('_', ' ').replace('-', ' ').trim()

        fun globToRegex(glob: String): Regex {
            val sb = StringBuilder()
            for (c in glob) {
                when (c) {
                    '*' -> sb.append(".*")
                    '?' -> sb.append('.')
                    else -> sb.append(Regex.escape(c.toString()))
                }
            }
            return Regex(sb.toString(), RegexOption.IGNORE_CASE)
        }
    }
}
